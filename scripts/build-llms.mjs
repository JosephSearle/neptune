#!/usr/bin/env node
// Builds llms.txt (an index, per llmstxt.org) and llms-full.txt (everything in one file) for agents.
//
// Sources:   README.md, components/*/README.md, the group in each preview's @dsCard comment
// Usage:     node scripts/build-llms.mjs           write both files
//            node scripts/build-llms.mjs --check   fail if either is out of date

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const RAW = "https://raw.githubusercontent.com/JosephSearle/neptune/main";
const read = (p) => readFileSync(join(root, p), "utf8");

const GROUP_ORDER = ["Layout", "Navigation", "Content", "Actions", "Forms", "Status"];

const components = readdirSync(join(root, "components"), { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(root, "components", d.name, "README.md")))
  .map((d) => {
    const readme = read(`components/${d.name}/README.md`);
    const preview = existsSync(join(root, "components", d.name, "preview.html")) ? read(`components/${d.name}/preview.html`) : "";
    const summary = readme.split("\n").find((l, i) => i > 0 && l.trim() && !l.startsWith("#"));
    const group = (preview.match(/@dsCard[^>]*group="([^"]+)"/) || [])[1] || "Other";
    return { name: d.name, readme, summary: summary.trim(), group };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const groups = [...new Set([...GROUP_ORDER, ...components.map((c) => c.group)])].filter((g) => components.some((c) => c.group === g));

const index = `# Neptune

> Joseph Searle's personal brand and design system: an engineer's notebook printed on paper. Classical serif (Newsreader) for ideas, monospace (IBM Plex Mono) for anything a machine would say, one electric blue for action. Two themes: Paper (light, default) and Deep (dark). Plain CSS: tokens as CSS variables plus \`np-\` component classes, no framework.

Rules an agent most often gets wrong:

- Load \`tokens.css\` then \`components/bundle.css\`, and \`components/neptune.js\` (deferred) for interactive components. Build from the \`np-\` components; never restyle them inline or invent new colours.
- Spend \`neptune\` (the blue) on one thing per view: the primary action, a link, the active item or the focus ring.
- Headings and body in serif; labels, buttons, nav, metadata and code in mono. Never paragraphs in mono, never buttons in serif.
- Square corners, 1px hairlines, no blurred shadows, no gradients, no emoji, no icons: use the typographic glyphs in the guide.
- Status always carries a word, never colour alone. Errors use \`aria-invalid\` and say what went wrong, then what to do.
- Copy is direct and imperative, sentence case, no marketing adjectives.

## Guide

- [Brand guide](${RAW}/README.md): voice, colour, type, space, layout, docs page recipe, slides, ornament, imagery, motion, accessibility, states, how to use it in code, versioning.
- [Changelog](${RAW}/CHANGELOG.md): every release, newest first, in Keep a Changelog format.
- [tokens.css](${RAW}/tokens.css): every token as a CSS variable for both themes, the system-dark default and print, plus a class per type style.
- [tokens.json](${RAW}/tokens.json): the source of truth for all tokens, each with a usage note.
- [components/bundle.css](${RAW}/components/bundle.css): every \`np-\` component class.
- [components/neptune.js](${RAW}/components/neptune.js): behaviour for Tabs, Tooltip, Toast, SearchDialog, Dialog, ThemeToggle and CodeCopy; no dependencies.

${groups
  .map(
    (g) =>
      `## Components: ${g}\n\n` +
      components
        .filter((c) => c.group === g)
        .map((c) => `- [${c.name}](${RAW}/components/${c.name}/README.md): ${c.summary}`)
        .join("\n"),
  )
  .join("\n\n")}

## Optional

- [DTCG tokens](${RAW}/tokens/dtcg/base.tokens.json): W3C Design Tokens 2025.10 export (with \`primitives\`, \`paper\` and \`deep\` files beside it) for Style Dictionary, Terrazzo or Figma variables.
- [Full text](${RAW}/llms-full.txt): the brand guide and every component README in one file.
- Previews: each component folder has a \`preview.html\` showing working markup, e.g. [Dialog](${RAW}/components/Dialog/preview.html).
`;

const full =
  `# Neptune: full reference\n\nThe brand guide followed by every component README. Generated by scripts/build-llms.mjs; edit the sources, not this file.\n\n` +
  `---\n\n${read("README.md").trim()}\n\n` +
  components.map((c) => `---\n\n${c.readme.trim()}\n\nSource: components/${c.name}/README.md · Preview: components/${c.name}/preview.html\n`).join("\n");

const outputs = { "llms.txt": index, "llms-full.txt": full };
const check = process.argv.includes("--check");
const stale = [];
for (const [p, text] of Object.entries(outputs)) {
  if (check) {
    if (!existsSync(join(root, p)) || read(p) !== text) stale.push(p);
  } else writeFileSync(join(root, p), text);
}
if (stale.length) {
  console.error(stale.map((p) => `✗ ${p} is out of date. Run: node scripts/build-llms.mjs`).join("\n"));
  process.exit(1);
}
console.log(check ? "✓ llms.txt and llms-full.txt are up to date" : `✓ Wrote llms.txt (${components.length} components) and llms-full.txt`);
